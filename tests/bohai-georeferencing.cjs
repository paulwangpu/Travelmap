const assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>JSON.parse(fs.readFileSync(p));
const doc=read('docs/bohai-shangjing-georeferencing.json').satelliteRevision;
const features=read('data/ancient-capital-research-extents.geojson').features.filter(f=>f.properties.family==='bohai');
assert.equal(features.length,18);
assert.ok(!features.some(f=>f.properties.sourceName.includes('玄武湖')));
assert.equal(doc.controlWgs84.length,4);
assert.ok(doc.newMeanMeters<doc.oldMeanMeters/2,'Independent palace image checks must improve substantially');
assert.ok(doc.validation.every(v=>v.newErrorMeters<70),'Palace alignment must stay within the documented image-check tolerance');
const outer=features.find(f=>f.properties.sourceId==='bohai-shangjing-plan2020-0').geometry.coordinates[0];
assert.deepEqual(outer[0],outer.at(-1));
const lat=outer.reduce((s,p)=>s+p[1]/outer.length,0)*Math.PI/180;
const projected=outer.map(p=>[p[0]*111320*Math.cos(lat),p[1]*111320]);
const area=Math.abs(projected.reduce((s,p,i)=>{const q=projected[(i+1)%projected.length];return s+p[0]*q[1]-q[0]*p[1];},0))/2e6;
assert.ok(area>15&&area<17.5,'Full outer-city scale should agree approximately with published archaeological dimensions');
const catalog=read('data/china-ancient-capitals.json');
const entries=[...catalog.items,...catalog.recordItems].filter(f=>f.siteNames?.includes('宁安上京')||f.siteName==='宁安上京');
assert.ok(entries.length);
assert.ok(entries.every(f=>f.lng===doc.newReferencePoint[0]&&f.lat===doc.newReferencePoint[1]));
assert.ok(features.every(f=>f.geometry.coordinates.flat(Infinity).every(Number.isFinite)));
console.log('PASS: Bohai independent alignment checks, outer-city scale, all 18 features and capital reference consistency');
