const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const app = fs.readFileSync(path.join(root, "app.js"), "utf8");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const data = JSON.parse(fs.readFileSync(path.join(root, "data", "plate-tectonics.geojson"), "utf8"));
assert.match(html, /id="showPlateTectonicsOnMap"/);
assert.match(html, /id="tectonicLegend"/);
assert.match(app, /function syncMapLibrePlateTectonicsOverlay/);
assert.ok(data.features.length >= 150);
const categories = new Set(data.features.map((feature) => feature.properties.category));
["subduction", "ridge", "transform", "rift", "fracture-zone", "orogenic-belt"].forEach((category) => assert.ok(categories.has(category)));
console.log("PASS: comprehensive EarthByte GPlates tectonic overlay is locally stored and wired");
