const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const code=fs.readFileSync(require.resolve('../great-wall.js'),'utf8');
const context={};vm.createContext(context);
vm.runInContext(code.replace('root.GreatWall={init,legend,sync,leaflet,categories};','root.GreatWall={landmarkTier,filtered,setData:d=>data=d,setConfig:c=>config=c};'),context);
const api=context.GreatWall;
assert.equal(api.landmarkTier({name:'山海关'}),2);
assert.equal(api.landmarkTier({name:'镇北台'}),1);
assert.equal(api.landmarkTier({name:'金山岭'}),2);
for(const name of ['紫荆关','红山堡','锁阳城','九门口','青龙峡','潘家口','黄花城关','水关'])assert.equal(api.landmarkTier({name}),1);
for(const name of ['南水关','北水关','北水关敌台','黄花城','红山堡附近烽火台'])assert.equal(api.landmarkTier({name}),0);
for(const name of ['山海关长城博物馆','山海关东一台','慕田峪村东092号敌台','小喜峰口'])assert.equal(api.landmarkTier({name}),0);
const original=JSON.parse(fs.readFileSync(require.resolve('../data/great-wall/features.geojson'),'utf8'));
const snapshot=JSON.stringify(original);
api.setData(original);api.setConfig({state:()=>({mapOverlays:{}})});
const rendered=api.filtered();assert.equal(rendered.features.length,original.features.length);
assert.equal(JSON.stringify(original),snapshot);
assert.equal(rendered.features.filter(f=>f.geometry.type==='Point'&&f.properties.name==='山海关'&&f.properties.labelRepresentative).length,1);
assert.ok(rendered.features.some(f=>f.properties.name==='老龙头'&&f.properties.landmarkTier===1));
api.setConfig({state:()=>({mapOverlays:{greatWallCategories:{pass:false}}})});
assert.ok(api.filtered().features.some(f=>f.properties.name==='山海关'&&f.properties.labelRepresentative));
assert.match(code,/\[\[0,11,12\],\[1,7,13\],\[2,5,14\]\]/);
assert.match(code,/'text-allow-overlap':false/);
assert.match(code,/'text-color':color/);
assert.ok(code.includes('color:${detailColor(p)}'));
assert.match(code,/leafletLabelCleanup=\(\)=>map.off/);
console.log('PASS: curated landmark tiers, exact names, representative labels, filter fallback, immutable data and renderer priorities');
